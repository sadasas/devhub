import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { createHash } from 'node:crypto'
import { pathToFileURL } from 'node:url'

const CACHE_NAME = 'devhub-v1'

export function collectAssets(distDir) {
  const entries = []
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name)
      const st = statSync(full)
      if (st.isDirectory()) {
        walk(full)
      } else if (st.isFile() && name !== 'sw.js') {
        const url = '/' + relative(distDir, full).split(sep).join('/')
        const revision = createHash('sha1').update(readFileSync(full)).digest('hex').slice(0, 10)
        entries.push({ url, revision })
      }
    }
  }
  walk(distDir)
  return entries.sort((a, b) => a.url.localeCompare(b.url))
}

export function renderServiceWorker(entries, cacheName = CACHE_NAME) {
  const precache = entries
    .map((entry) => `    ${JSON.stringify(`${entry.url}?v=${entry.revision}`)}`)
    .join(',\n')
  return `/* DevHub service worker — generated by scripts/sw-precache.mjs (npm run build -> postbuild). Do not edit. */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = [
${precache}
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/index.html', { ignoreSearch: true })));
    return;
  }
  event.respondWith(
    caches.match(request).then((cached) => cached ?? fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        void caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })),
  );
});
`
}

export function writeServiceWorker(distDir) {
  const entries = collectAssets(distDir)
  writeFileSync(join(distDir, 'sw.js'), renderServiceWorker(entries), 'utf8')
  return entries.length
}

const isMain =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href

if (isMain) {
  const distDir = process.argv[2] ?? join(process.cwd(), 'dist')
  const count = writeServiceWorker(distDir)
  console.log(`sw.js written to ${distDir} (${count} precached assets, cache ${CACHE_NAME})`)
}